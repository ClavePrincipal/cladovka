#!/usr/bin/env bash
# NOIR test stand: one-command install on a fresh Ubuntu / Debian VPS.
#
#   git clone -b claude/casino-website-design-nzo80n https://github.com/ClavePrincipal/cladovka.git
#   cd cladovka/casino-noir
#   sudo bash deploy/install.sh <domain> <admin-email>
#
# Runs in test mode (NODE_ENV=development): sandbox payments and sandbox KYC, no real money.
# Safe to re-run: keeps the existing .env, database and admin account, and rebuilds the app.
set -euo pipefail
cd "$(dirname "$0")/.."

DOMAIN="${1:-}"; ADMIN_EMAIL="${2:-}"
if [ -z "$DOMAIN" ] || [ -z "$ADMIN_EMAIL" ]; then
  echo "Использование: sudo bash deploy/install.sh <домен> <e-mail администратора>"
  echo "Пример:        sudo bash deploy/install.sh noir-test.example.com me@example.com"
  exit 1
fi
say() { printf '\n\033[1;33m==> %s\033[0m\n' "$*"; }

if ! command -v docker >/dev/null 2>&1; then
  say "Устанавливаю Docker"
  curl -fsSL https://get.docker.com | sh
fi

if command -v ufw >/dev/null 2>&1; then
  say "Настраиваю файрвол: открыты только SSH, HTTP и HTTPS"
  ufw allow 22/tcp >/dev/null && ufw allow 80/tcp >/dev/null && ufw allow 443/tcp >/dev/null
  ufw --force enable >/dev/null
fi

if ! getent hosts "$DOMAIN" >/dev/null 2>&1; then
  echo "Внимание: домен $DOMAIN пока не указывает ни на какой IP. Создайте у регистратора A-запись на IP этого сервера,"
  echo "иначе HTTPS-сертификат не выпустится. Установка продолжится, сертификат появится, когда DNS обновится."
fi

if [ ! -f .env ]; then
  say "Создаю .env со случайными секретами"
  hex() { openssl rand -hex "$1"; }
  umask 077
  cat > .env <<EOF
# Generated by deploy/install.sh on $(date -u +%F). Test stand: sandbox payments and KYC, no real money.
NODE_ENV=development
DOMAIN=$DOMAIN
PUBLIC_URL=https://$DOMAIN
COOKIE_SECURE=true
TRUST_PROXY=true
PII_KEY=$(hex 32)
LOOKUP_KEY=$(hex 32)
METRICS_TOKEN=$(hex 24)
PAYMENT_WEBHOOK_SECRET=$(hex 24)
KYC_WEBHOOK_SECRET=$(hex 24)
DB_PASSWORD=$(hex 16)
GRAFANA_PASSWORD=$(hex 12)
CURRENCY=KZT
EOF
  umask 022
else
  say ".env уже есть, оставляю его (секреты и данные сохраняются)"
fi

# Prometheus reads the metrics token from a file (the container runs as 'nobody').
grep '^METRICS_TOKEN=' .env | cut -d= -f2 | tr -d '\n' > deploy/prometheus/metrics_token
chmod 644 deploy/prometheus/metrics_token
mkdir -p backups

say "Собираю и запускаю (первый запуск занимает несколько минут)"
docker compose up -d --build
# Config files are bind-mounted: running containers do not notice changes after 'git pull', so reload them.
docker compose exec -T proxy caddy reload --config /etc/caddy/Caddyfile >/dev/null 2>&1 || docker compose restart proxy
docker compose kill -s HUP prometheus >/dev/null 2>&1 || true

say "Жду, пока приложение запустится"
ok=""
for _ in $(seq 1 90); do
  if docker compose exec -T app node -e "fetch('http://127.0.0.1:8080/ready').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" 2>/dev/null; then ok=1; break; fi
  sleep 2
done
if [ -z "$ok" ]; then echo "Приложение не запустилось. Логи: docker compose logs app"; exit 1; fi

say "Добавляю демо-линию спортивных событий"
docker compose exec -T app node src/scripts/seed.js

EMAIL_LC=$(printf '%s' "$ADMIN_EMAIL" | tr '[:upper:]' '[:lower:]')
if [ -z "$(docker compose exec -T db psql -U noir -d noir -tAc "SELECT 1 FROM staff WHERE email = '${EMAIL_LC//\'/}'")" ]; then
  say "Создаю администратора бэк-офиса. СОХРАНИТЕ пароль и секрет 2FA: они показываются один раз"
  docker compose exec -T app node src/scripts/create-staff.js "$EMAIL_LC" "Администратор" admin
else
  say "Администратор $EMAIL_LC уже есть"
fi

GRAFANA_PASSWORD=$(grep '^GRAFANA_PASSWORD=' .env | cut -d= -f2)
cat <<EOF

Готово.
  Сайт:       https://$DOMAIN
  Бэк-офис:   https://$DOMAIN/admin/   (вход: e-mail, пароль и код из приложения-аутентификатора)
  Grafana:    на своём компьютере выполните  ssh -L 3000:127.0.0.1:3000 <пользователь>@<IP сервера>
              и откройте http://localhost:3000  (логин admin, пароль $GRAFANA_PASSWORD)

Это тестовый стенд: оплата и верификация работают через песочницу, реальные деньги не списываются.
Обновить сайт после изменений в коде:  git pull && sudo bash deploy/install.sh $DOMAIN $ADMIN_EMAIL
EOF
