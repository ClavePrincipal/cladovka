def money(value):
    """12345.6 → «12 346 ₽» — так большие числа читать проще."""
    return f"{value:,.0f}".replace(",", " ") + f" {CURRENCY}"


def names(table):
    """Названия товаров через запятую или «нет», если таблица пустая."""
    return ", ".join(table["Товар"]) or "нет"


def print_summary(purchase, profit, today):
    print()
    print(f"Прогноз на {today:%d.%m.%Y}, товаров: {len(purchase)}")
    print()
    short = purchase[["Статус", "Товар", "Прогноз, шт/день", "Хватит на, дней", "Сколько заказать, шт"]]
    print(short.to_string(index=False))
    print()

    urgent = purchase[purchase["Статус"] == URGENT]
    to_order = purchase[purchase["Статус"].isin([URGENT, ORDER])]
    overstock = purchase[purchase["Статус"] == OVERSTOCK]
    losses = profit[profit["Вывод"] == LOSS]

    print(f"Срочно заказать ({len(urgent)}): {names(urgent)}")
    print(f"Позиций к заказу: {len(to_order)}, на сумму {money(to_order[f'Сумма закупки, {CURRENCY}'].sum())}")
