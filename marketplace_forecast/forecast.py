def make_history(product_sales):
    """
    Превращает продажи одного товара в «чистую» историю спроса.

    Главная идея всего проекта. Если товара НЕ БЫЛО на складе, то 0 продаж
    в этот день означает «нечего было продать», а не «никто не хотел купить».
    Если считать такие дни нулевым спросом, прогноз занизится, мы закупим
    меньше, товар снова закончится — замкнутый круг. Большинство продавцов,
    которые считают «на глаз» или в Excel, попадают именно в него.

    Поэтому дни, когда остаток на конец дня = 0, помечаем как «неизвестно»
    (NaN = Not a Number, «пусто»), и дальше они просто не участвуют в расчётах.
    Мы берём именно конец дня: если к вечеру товар кончился, днём он мог
    закончиться, и продажи за этот день неполные.
    """
    # .where(условие) оставляет значение там, где условие верно,
    # а где неверно — ставит NaN.
    return product_sales["sold"].where(product_sales["stock"] > 0)


def forecast_daily_demand(history):
    """
    ПРОГНОЗ: сколько штук в день будет продаваться в ближайшее время.

    Метод самый простой и понятный: среднее за последние HISTORY_DAYS дней,
    когда товар был в наличии. Плюсы: легко объяснить клиенту, трудно сломать,
    редко ошибается «катастрофически». Минус: если продажи быстро растут или
    падают, среднее отстаёт от реальности (это видно в check_accuracy.py).

    Это ЕДИНСТВЕННОЕ место, где живёт модель. Хотите прогноз точнее —
    меняйте только эту функцию, запускайте check_accuracy.py и смотрите,
    стала ли ошибка меньше. Остальной код трогать не нужно.

    Возвращает три числа:
      daily_mean — прогноз: сколько штук в день
      daily_std  — насколько продажи «скачут» день ото дня (нужно для страхового запаса)
      n_days     — по скольким дням посчитано (мало дней = прогноз ненадёжный)
    """
    # dropna() выкидывает дни без товара, tail(28) берёт 28 последних из оставшихся.
    known_days = history.dropna().tail(HISTORY_DAYS)
    n_days = len(known_days)

    if n_days == 0:
        return 0.0, 0.0, 0

    daily_mean = known_days.mean()
    # Стандартное отклонение — «средний разброс» вокруг среднего.
    # По одному дню разброс посчитать нельзя, поэтому тогда 0.
    daily_std = known_days.std() if n_days > 1 else 0.0
    return daily_mean, daily_std, n_days


