def main():
    print("Читаю данные...")
    products, sales = load_data()

    # «Сегодня» = день после последней даты в данных, а не дата на компьютере.
    # Так результат не зависит от того, в какой день вы запустили скрипт,
    # и прогноз всегда начинается сразу после известных данных.
    today = sales["date"].max() + pd.Timedelta(days=1)

    # Идём по товарам по одному. Цикл медленнее «продвинутых» приёмов pandas,
    # зато его легко читать и отлаживать, а для тысяч товаров скорости хватает.
    purchase_rows = []
    profit_rows = []
    for _, product in products.iterrows():
        product_sales = sales[sales["sku"] == product["sku"]]   # строки только этого товара
        purchase_rows.append(plan_purchase(product, product_sales, today))
        profit_rows.append(calc_profit(product, product_sales))

    # Список словарей → таблица: каждый словарь становится строкой.
    purchase = pd.DataFrame(purchase_rows)
    profit = pd.DataFrame(profit_rows)

    # Сортировка закупок: сначала по срочности статуса, внутри — кто раньше закончится.
    purchase["_order"] = purchase["Статус"].map(STATUS_ORDER)
    purchase = purchase.sort_values(["_order", "Хватит на, дней"]).drop(columns="_order")

    # Прибыль: самые убыточные сверху, чтобы сразу бросались в глаза.
    profit = profit.sort_values(f"Прибыль, {CURRENCY}")

    save_excel(purchase, profit, RESULT_FILE)
    print_summary(purchase, profit, today)


if __name__ == "__main__":
    main()
