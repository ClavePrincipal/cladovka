def plan_purchase(product, product_sales, today):
    """
    Решает, когда и сколько заказать. Возвращает одну строку отчёта (словарь).

    Логика на примере. Продаём 10 шт/день, поставка едет 14 дней,
    на складе 200 шт, закупка должна покрывать 30 дней:
      • Хватит на: 200 / 10 = 20 дней.
      • Пока едет поставка, продадим 10 × 14 = 140 шт.
        К её приезду останется 200 − 140 = 60 шт.
      • Нужно, чтобы после приезда хватило на 30 дней (10 × 30 = 300 шт)
        плюс страховой запас. Если продажи «скачут» в среднем на ±3 шт/день,
        он равен 1.65 × 3 × √(14 + 30) ≈ 33 шт (формула ниже).
      • Заказать: 300 + 33 − 60 = 273 шт.
    """
    lead_time = product["lead_time_days"]
    history = make_history(product_sales)
    daily, daily_std, n_days = forecast_daily_demand(history)

    # Остаток на последний день данных; если строк нет — 0.
    stock = product_sales["stock"].iloc[-1] if len(product_sales) > 0 else 0
    # Товар «в пути» скоро приедет, поэтому считаем его как уже имеющийся.
    available = stock + product["in_transit"]

    # --- Упущенные продажи ---
    # Сколько дней из последних REPORT_DAYS календарных дней товара не было.
    # В эти дни мы продали бы примерно столько, сколько в обычный день.
    stockout_days = int(history.tail(REPORT_DAYS).isna().sum())
    lost_revenue = stockout_days * daily * product["price"]

    # Примечания — подсказки человеку, на что обратить внимание.
    notes = []
    if len(product_sales) == 0:
        notes.append("Нет строк в sales.csv: проверьте, совпадает ли артикул")
    else:
        if stock == 0:
            notes.append("Товара нет на складе прямо сейчас")
        if stockout_days > 0:
            notes.append(f"Товара не было {stockout_days} дн. из последних {REPORT_DAYS}")
        if n_days < MIN_HISTORY_DAYS:
            notes.append(f"Мало истории ({n_days} дн.), проверьте прогноз вручную")

    # Строка отчёта. Колонки в Excel пойдут в том же порядке, что и здесь.
    # None — «пока пусто»: эти поля заполним ниже, если у товара есть продажи.
    row = {
        "Статус": NO_SALES,
        "Артикул": product["sku"],
        "Товар": product["name"],
        "Прогноз, шт/день": round(daily, 1),
        "Остаток, шт": stock,
        "В пути, шт": product["in_transit"],
        "Хватит на, дней": None,
        "Закончится": None,
        "Заказать до": None,
        "Сколько заказать, шт": 0,
        f"Сумма закупки, {CURRENCY}": 0,
        "Страховой запас, шт": None,
        f"Упущенная выручка за {REPORT_DAYS} дн., {CURRENCY}": round(lost_revenue),
        f"Деньги в товаре, {CURRENCY}": stock * product["cost"],
        "Примечание": "; ".join(notes),
    }

    # Если продаж не было, делить на прогноз нельзя (деление на 0) — выходим.
    if daily == 0:
        return row

    # --- Страховой запас ---
    # Продажи «скачут»: в один день 6, в другой 14. Страховой запас — подушка
    # на случай, если продажи окажутся выше среднего, пока мы ждём поставку.
    # Формула: Z × разброс за день × √(число дней риска).
    # Дни риска = срок поставки + дни до следующего заказа (COVER_DAYS):
    # всё это время мы не можем быстро пополнить склад.
    # Почему корень, а не просто «умножить на дни»: удачные и неудачные дни
    # частично гасят друг друга. Поэтому разброс за 44 дня (14 + 30) не в 44 раза
    # больше разброса за день, а примерно в √44 ≈ 6.6 раза.
    safety_stock = Z * daily_std * math.sqrt(lead_time + COVER_DAYS)

    # --- Сроки ---
    days_left = available / daily   # на сколько дней хватит

    # Сколько останется к приезду поставки. В минус уйти нельзя: если товар
    # кончится раньше, покупатели просто уйдут к конкурентам, «долга» не будет.
    left_at_arrival = max(available - daily * lead_time, 0)

    # Через сколько дней остаток опустится до «точки заказа» — уровня, когда
    # запаса хватает ровно на время поставки плюс страховой запас.
    # Если число ≤ 0 — заказывать надо уже сегодня.
    days_until_order = (available - daily * lead_time - safety_stock) / daily

    # --- Статус: проверяем по очереди, от самого тревожного ---
    if days_left < lead_time:
        row["Статус"] = URGENT       # закончится раньше, чем успеет приехать новая поставка
    elif days_until_order <= 7:
        row["Статус"] = ORDER        # пора заказывать: сегодня или на этой неделе
    elif days_left > OVERSTOCK_DAYS:
        row["Статус"] = OVERSTOCK    # товара слишком много
    else:
        row["Статус"] = OK

    # --- Сколько заказать (только если пора) ---
    # Нужно на COVER_DAYS дней + страховой запас − то, что останется к приезду.
    # Считаем, что заказ делается сегодня. math.ceil округляет вверх: 272.3 → 273.
    order_qty = 0
    if row["Статус"] in (URGENT, ORDER):
        order_qty = max(math.ceil(daily * COVER_DAYS + safety_stock - left_at_arrival), 0)

    # pd.Timedelta(days=...) — «промежуток в N дней»; его можно прибавить к дате.
    # min(..., 3650) — не дальше 10 лет. Если товар почти не продаётся, «хватит на»
    # может выйти в сотни лет, а календарь pandas заканчивается на 2262 году.
    stockout_date = today + pd.Timedelta(days=min(days_left, 3650))
    order_date = today + pd.Timedelta(days=min(max(days_until_order, 0), 3650))

    row["Хватит на, дней"] = round(days_left)
    row["Закончится"] = stockout_date.strftime("%d.%m.%Y")
    row["Заказать до"] = order_date.strftime("%d.%m.%Y")
    row["Сколько заказать, шт"] = order_qty
    row[f"Сумма закупки, {CURRENCY}"] = order_qty * product["cost"]
    row["Страховой запас, шт"] = math.ceil(safety_stock)
    return row


