# Папка, где лежит этот файл. Через неё ищем данные, поэтому скрипт
# сработает, даже если запустить его из другой папки.
HERE = Path(__file__).parent
DATA_DIR = HERE / "data"
RESULT_FILE = HERE / "results" / "zakupki.xlsx"

# По скольким последним дням (когда товар БЫЛ в наличии) считаем прогноз.
#   14 — прогноз быстрее замечает рост и падение, но сильнее «скачет».
#   56 — прогноз спокойнее, но медленнее реагирует на изменения.
#   28 — середина: ровно 4 недели, будни и выходные учтены поровну.
HISTORY_DAYS = 28

# Если дней с наличием меньше этого, прогноз ненадёжен: помечаем «мало истории».
MIN_HISTORY_DAYS = 14

# За сколько последних календарных дней считаем прибыль и упущенную выручку.
# Это отдельная настройка: можно экспериментировать с HISTORY_DAYS для
# прогноза, а период отчёта для клиента останется тем же.
REPORT_DAYS = 28

# На сколько дней продаж должно хватить одной закупки.
# Обычно это то, как часто вы заказываете у поставщика: раз в месяц → 30.
COVER_DAYS = 30

# Коэффициент для страхового запаса. Чем он больше, тем реже товар
# заканчивается, но тем больше денег лежит на складе.
#   1.28 → товар закончится примерно в 1 закупке из 10  (уровень сервиса 90%)
#   1.65 → примерно в 1 закупке из 20                   (уровень сервиса 95%)
#   2.33 → примерно в 1 закупке из 100                  (уровень сервиса 99%)
Z = 1.65

# Если остатка хватит дольше, чем на столько дней, это излишек: деньги
# заморожены в товаре, а маркетплейс может брать плату за хранение.
OVERSTOCK_DAYS = 90

# Налог, % от выручки. Пример: в России на УСН «Доходы» это 6%. Поставьте свою ставку.
TAX_PCT = 6

CURRENCY = "₽"

# Статусы товара в плане закупок.
URGENT = "СРОЧНО"         # закончится раньше, чем приедет новая поставка
ORDER = "ЗАКАЗАТЬ"        # пора заказывать: сегодня или в ближайшие 7 дней
OK = "ОК"                 # запаса хватает
OVERSTOCK = "ИЗЛИШЕК"     # товара слишком много
NO_SALES = "НЕТ ПРОДАЖ"   # продаж не было, прогнозировать не из чего

# Выводы по прибыли.
LOSS = "УБЫТОК"
LOW_MARGIN = "НИЗКАЯ МАРЖА"
GOOD = "НОРМА"

# Порядок сортировки: срочное сверху.
STATUS_ORDER = {URGENT: 1, ORDER: 2, OVERSTOCK: 3, OK: 4, NO_SALES: 5}

# Цвета заливки в Excel (код цвета RRGGBB): красный, жёлтый, зелёный, голубой.
COLORS = {URGENT: "FFC7CE", ORDER: "FFEB9C", OK: "C6EFCE", OVERSTOCK: "DDEBF7",
          LOSS: "FFC7CE", LOW_MARGIN: "FFEB9C", GOOD: "C6EFCE"}


