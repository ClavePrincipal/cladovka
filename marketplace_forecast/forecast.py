def save_excel(purchase, profit, path):
    """Сохраняет три листа в один Excel-файл и делает их удобными для чтения."""
    path.parent.mkdir(exist_ok=True)   # создать папку results, если её нет
    help_table = pd.DataFrame(HELP_ROWS, columns=["Что", "Что значит"])

    # ExcelWriter позволяет записать несколько листов в один файл.
    # Конструкция with сама закроет и сохранит файл в конце.
    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        purchase.to_excel(writer, sheet_name="Закупки", index=False)
        profit.to_excel(writer, sheet_name="Прибыль", index=False)
        help_table.to_excel(writer, sheet_name="Как читать", index=False)

        for sheet in writer.sheets.values():
            beautify(sheet)


def beautify(sheet):
    """Оформление: жирная закреплённая шапка, ширина колонок, цвет статусов."""
    sheet.freeze_panes = "A2"   # шапка остаётся на месте при прокрутке вниз
    for cell in sheet[1]:       # sheet[1] — первая строка листа, то есть шапка
        cell.font = Font(bold=True)

    for column in sheet.columns:
        # Ширина колонки = длина самого длинного текста в ней (но не больше 60).
        longest = max(len(str(cell.value)) if cell.value is not None else 0 for cell in column)
        sheet.column_dimensions[column[0].column_letter].width = min(longest + 2, 60)

        # Красим ячейки со статусами и выводами.
        for cell in column[1:]:            # [1:] — пропускаем шапку
            color = COLORS.get(cell.value)
            if color:
                cell.fill = PatternFill(start_color=color, end_color=color, fill_type="solid")


