# ШАГ 4. Реальная прибыль (юнит-экономика)
# ==========================================================================

def calc_profit(product, product_sales):
    """
    Считает, сколько товар реально заработал за последние REPORT_DAYS дней.

    Частая ловушка продавцов: «покупаю за 150, продаю за 590 — зарабатываю 440».
    На деле из цены вычитаются комиссия маркетплейса, логистика, налог и реклама.
    Иногда после всех вычетов товар оказывается убыточным, а продавец этого
    не видит, потому что выручка растёт.
    """
    last_days = product_sales.tail(REPORT_DAYS)   # последние REPORT_DAYS строк = дней (строки отсортированы по дате)
    sold = last_days["sold"].sum()

    revenue = sold * product["price"]                          # выручка
    commission = revenue * product["commission_pct"] / 100    # комиссия маркетплейса
    logistics = sold * product["logistics"]                    # доставка до покупателя
    cost_of_goods = sold * product["cost"]                     # себестоимость проданного
    tax = revenue * TAX_PCT / 100                              # налог
    ads = last_days["ad_spend"].sum()                          # реклама

    profit = revenue - commission - logistics - cost_of_goods - tax - ads

    # Проверка «if revenue > 0» защищает от деления на ноль, если продаж не было.
    margin_pct = profit / revenue * 100 if revenue > 0 else 0
    ads_pct = ads / revenue * 100 if revenue > 0 else 0       # ДРР — доля рекламных расходов
    profit_per_unit = profit / sold if sold > 0 else 0

    # Вывод и объяснение «почему» — главное для клиента.
    if sold == 0:
        verdict, reason = NO_SALES, "Нечего оценивать"
    elif profit < 0 and profit + ads > 0:
        verdict, reason = LOSS, "Без рекламы товар был бы прибыльным: снизьте ставки или ДРР"
    elif profit < 0:
        verdict, reason = LOSS, "Убыток даже без рекламы: пересмотрите цену или поставщика"
    elif margin_pct < 10:
        verdict, reason = LOW_MARGIN, "Меньше 10% с выручки: любой рост расходов уведёт в минус"
    else:
        verdict, reason = GOOD, ""

    return {
        "Вывод": verdict,
        "Артикул": product["sku"],
        "Товар": product["name"],
        "Продано, шт": sold,
        f"Выручка, {CURRENCY}": round(revenue),
        f"Комиссия МП, {CURRENCY}": round(commission),
        f"Логистика, {CURRENCY}": round(logistics),
        f"Себестоимость, {CURRENCY}": round(cost_of_goods),
        f"Налог, {CURRENCY}": round(tax),
        f"Реклама, {CURRENCY}": round(ads),
        f"Прибыль, {CURRENCY}": round(profit),
        f"Прибыль с 1 шт, {CURRENCY}": round(profit_per_unit),
        "Маржа, %": round(margin_pct, 1),
        "ДРР, %": round(ads_pct, 1),
        "Почему": reason,
    }


