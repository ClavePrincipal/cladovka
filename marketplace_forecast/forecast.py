"""
==========================================================================
 КЛАДОВКА — прогноз продаж и план закупок для продавца на маркетплейсе
==========================================================================

Что делает скрипт:
  1. Читает данные магазина:
       data/products.csv — справочник товаров: цена, себестоимость, комиссия...
       data/sales.csv    — продажи и остатки за каждый день
  2. Для каждого товара прогнозирует, сколько штук в день будет продаваться.
  3. Считает, на сколько дней хватит остатка, когда и сколько заказать.
  4. Считает реальную прибыль: после комиссии, логистики, налога и рекламы.
  5. Сохраняет отчёт в Excel: results/zakupki.xlsx. Этот файл можно отдать клиенту.

Запуск (в терминале, из папки marketplace_forecast):
    python forecast.py

Как читать код: сверху настройки, потом функции-шаги (ШАГ 1, ШАГ 2...),
в самом низу main(), который вызывает шаги по порядку.
Удобнее всего начать с main(): там видна вся картина целиком.
"""

